-- Backstop for three rules the API also enforces, so a future code path cannot break them:
--   1. a saved entry never goes back to draft;
--   2. created_at (when the writing began) never changes, whatever an UPDATE says;
--   3. an entry never changes owner.
CREATE OR REPLACE FUNCTION journal_entries_guard_update() RETURNS trigger AS $$
BEGIN
  IF OLD.status = 'saved' AND NEW.status = 'draft' THEN
    RAISE EXCEPTION 'journal_entries: a saved entry cannot return to draft' USING ERRCODE = 'check_violation';
  END IF;
  IF NEW.user_id IS DISTINCT FROM OLD.user_id THEN
    RAISE EXCEPTION 'journal_entries: an entry cannot change owner' USING ERRCODE = 'check_violation';
  END IF;
  NEW.created_at := OLD.created_at;
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;
