import type { Metadata } from 'next';
import { Container, Section } from '@tnsi/ui';
import { ReturnPathPractice } from '@/components/return-path/return-path-practice';
import { JsonLd } from '@/components/seo/json-ld';
import { SiteFooter } from '@/components/layout/site-footer';
import { SiteHeader } from '@/components/layout/site-header';
import { getReturnPathContent } from '@/content/cms/loaders';
import { createBreadcrumbJsonLd, createPageMetadata, createWebPageJsonLd } from '@/lib/seo';

/**
 * The Return Path - free public practice (lead magnet). Level 1 only;
 * Levels 2-3 show the members message. No sign-in, nothing stored.
 *
 * NOT LAUNCHED: deliberately `noindex`, absent from the sitemap and linked
 * from nowhere until Caroline approves the name, copy, consent wording and
 * route (PROJECT.md decision log, 2026-10-12). To launch: drop `noIndex`,
 * add the route to `STATIC_ROUTES` in app/sitemap.ts, and link to it.
 */
const PATH = '/the-return-path';
const PUBLIC_LEVELS = [1] as const;
const LAUNCHED = false;

export async function generateMetadata(): Promise<Metadata> {
  const content = await getReturnPathContent();
  // Title tag and meta description are approved separately; until then the
  // page's own title and description stand in.
  return createPageMetadata({
    title: content.intro.title,
    description: content.intro.description,
    path: PATH,
    noIndex: !LAUNCHED,
    // The labyrinth OG image generated by ./opengraph-image.tsx.
    imagePath: `${PATH}/opengraph-image`,
  });
}

export default async function TheReturnPathPage() {
  const content = await getReturnPathContent();

  const jsonLd = [
    createWebPageJsonLd({
      title: content.intro.title,
      description: content.intro.description,
      path: PATH,
    }),
    createBreadcrumbJsonLd([
      { name: 'Home', path: '/' },
      { name: content.intro.title, path: PATH },
    ]),
  ];

  return (
    <>
      <JsonLd data={jsonLd} />
      <SiteHeader />
      <main id="main-content">
        <Section spacing="xl">
          <Container size="xl">
            <div className="mx-auto max-w-[720px]">
              <ReturnPathPractice
                context="public"
                content={content}
                allowedLevels={[...PUBLIC_LEVELS]}
              />
            </div>
          </Container>
        </Section>
      </main>
      <SiteFooter />
    </>
  );
}
